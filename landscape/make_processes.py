BMESON_NOTE = """**The cross section is dominated by a dimensionally inconsistent term in the
original code, and should not be used as a rate without reading this.** The
Julia's production sum adds `1e-3 * bmesondecay` -- a dimensionless
branching-ratio-like quantity -- to two terms that are cross sections in barns
(`ScalarProductionshare.jl` lines 66-81 and 143-153). It contributes
{bmeson:.4g} pb against {direct:.4g} pb of genuine direct production, a factor
{ratio:.0f}. Because it is nonzero only below 4.7 GeV it also skews *which*
scalar is produced, not just the normalisation. It is reproduced as written,
because it is what defines the authors' L-A; pass `--no-bmeson-term` to
`landscape.make_lhe` to drop it, which gives {without:.4g} pb.
"""

RETUNE_NOTE = """lambda is retuned from the shipped 1e-4 to {lam:g}, which is what puts this
point at the Higgs signal-strength bound instead of three orders of magnitude
below it. Gamma(h -> phi phi) goes as lambda^2 and nothing else in the chain
depends on lambda, so the retuning is a closed form -- `landscape/retune.py`.

The bound is applied to the **physical** BR. The Julia normalises to
Gamma_bb(pole) x 1.89 = 8.13e-3 GeV against a true SM width of 4.1e-3, so
tuning its number to 0.1 would land at a physical 0.17, over the bound
(deviation 7d).

lambda' is deliberately **not** scaled with lambda. Every hidden-sector width
carries lambda'^2 and every Standard Model width carries theta^2 ~ lambda^2, so
raising lambda alone reweights hidden against SM -- but the hidden channels
already hold at least 1 - 6.9e-8 of every above-threshold scalar's width at the
shipped point, and a factor 729 in lambda^2 leaves them at 1 - 5.0e-5. The
largest change in hidden fraction anywhere in the spectrum is 5.0e-5, and 400
cascades driven by the same uniform stream come out element-for-element
identical, so multiplicity and flavour composition are unchanged.
`landscape/tests/test_tier8_retune.py` asserts both.
"""

SHIPPED_NOTE = """lambda is the **shipped** 1e-4, not the retuned {retuned:g} that `L-B` uses.
The rate is 730x lower, but that is not why this point exists: below the
hidden-pair threshold a scalar has no hidden channel open, so its width is pure
mixing and ctau goes as lambda^-2. At the shipped lambda those scalars live
730x longer, and the sample is **displaced** where L-B is prompt. It is a
different signature, not a weaker L-B.
"""

DISPLACED_LIFE = """Every cascade *terminates* on a sub-threshold scalar, so this displacement is
not a tail -- it is where essentially all the visible partons come from.
"""

PROMPT_LIFE = """The sub-threshold scalars still carry the longest lifetimes, but at this lambda
they are microns, so the sample is prompt for all detector purposes. `L-B-displaced`
is the same topology with the shipped lambda, where the same scalars reach
millimetres.
"""

