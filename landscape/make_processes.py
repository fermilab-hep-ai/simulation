"""
Emit the ``processes/landscape_*`` directories for the S1b benchmarks.

The other AIDA-Scout signals are written by ``make_signal_cards.py`` at the
repository root, but the landscape points are not a card-writing task: their
hard process is the Python cascade generator in this package, and the card only
tells Pythia where to find the LHE it produces.  This script is the landscape
equivalent -- edit it, not the generated files.

    python3 -m landscape.make_processes            # writes into processes/

Each point gets three files:

  <name>_pythia_card.dat   Pythia settings, with _LHEFILE_ / NEVENTS / NSEED
                           placeholders that run.sh substitutes
  <name>_lhe_args.dat      one line of arguments for landscape.make_lhe; its
                           presence is what makes run.sh do the LHE pre-step
  README.md                parameters, lifetimes, and which seeds it should fail

The spectrum seed is deliberately NOT in the args file as a run-time knob: it
is part of the benchmark definition in params.BENCHMARKS, so every parallel job
of a point shares one landscape realisation.  L-D varies the realisation by
being three separate benchmarks.
"""

