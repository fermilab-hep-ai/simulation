LHE_NOTE = """
## What is in the LHE

The hidden scalars are written into the record, not just the final partons.
They share one PDG id (9000006) and each carries its own mass and its own
`VTIMUP`, because an LHE has nowhere else to put a per-particle displacement
and the cascade's decay vertices are the physics.

`LesHouches:setLifetime = 1` in the card is load-bearing: it is Pythia's
default, but `= 2` silently discards `VTIMUP` and collapses every hidden-scalar
decay vertex to the origin, making the sample prompt with no error. Verified by
A/B: with `= 1` the scalar decay vertices reach 232 mm; with `= 2` they are all
exactly zero.

Colour is connected **locally**: each phi -> q qbar is its own singlet with one
fresh tag, each phi -> g g its own closed loop with two. Connecting colour
across the cascade would string the whole event together and materially change
the hadronic activity.
"""


def readme(tag, name, measured=None):
    model, mode, seed = benchmark_entry(tag)
    consts = SMConstants()
    spectrum = draw_spectrum(model, seed)
    measured = measured or {}

    if mode == "direct":
        xs, _ = P.cross_sections(spectrum, consts, model)
        xsec = sum(xs) * 1e12
        h, d, b = P.production_breakdown(spectrum, consts, model,
                                         P.SIGMA_H_CROSSSECTIONS)
        norm_note = BMESON_NOTE.format(
            bmeson=b * 1e12, direct=d * 1e12,
            ratio=(b / d) if d else float("nan"),
            without=(h + d) * 1e12)
    else:
        xs, _ = P.cross_sections_higgs_only(spectrum, consts, model)
        xsec = sum(xs) * 1e12
        if model.lam == LAMBDA_RETUNED:
            norm_note = RETUNE_NOTE.format(lam=model.lam)
        else:
            norm_note = SHIPPED_NOTE.format(retuned=LAMBDA_RETUNED)

    br_phys = RT.br_h_to_bsm_physical(spectrum, consts, model)
    life = LT.summarise(spectrum, consts, model)
    life_note = (DISPLACED_LIFE if life["below_median_mm"] > 0.1
                 else PROMPT_LIFE)

    notes = LHE_NOTE + measured.get("notes", "") + DOWNSTREAM

    return README.format(
        name=name, tag=tag, what=measured.get("what", one_line(tag)),
        N=model.N, lam=model.lam, lamp=model.lam_prime,
        ratio=model.lam_prime / model.lam,
        mstar=model.M_star, vev2=model.vev_2, theta=model.mixing(consts),
        mlow=model.mass_low, mhigh=model.mass_high, seed=seed,
        mode=("direct ggF (+ the Julia's B-meson term)" if mode == "direct"
              else "gg -> h -> phi_i phi_j"),
        xsec=xsec, br_phys=br_phys,
        br_code=P.br_h_to_bsm(spectrum, consts, model),
        verdict=("within" if br_phys <= RT.BR_BOUND * (1 + 1e-9)
                 else "VIOLATED"),
        norm_note=norm_note,
        lifetimes=LT.format_summary(spectrum, consts, model, label=tag),
        life_note=life_note,
        menu=MENU.format(**measured.get("menu", DEFAULT_MENU)),
        notes=notes)


# Until a point has been measured, say so rather than guessing.
DEFAULT_MENU = {k: "to measure" for k in
                ("ht", "jet", "quad", "bph", "mu44", "ele", "pho", "tau",
                 "met")}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outdir", default="processes")
    ap.add_argument("--only", default=None,
                    help="write just this benchmark tag")
    args = ap.parse_args(argv)

    from . import measured as MEAS

    written = []
    for tag in sorted(BENCHMARKS):
        if args.only and tag != args.only:
            continue
        name = PROCESS_NAMES[tag]
        d = os.path.join(args.outdir, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "{0}_pythia_card.dat".format(name)), "w") as fh:
            fh.write(card(tag) + jet_filter_block(name))
        with open(os.path.join(d, "{0}_lhe_args.dat".format(name)), "w") as fh:
            fh.write(lhe_args(tag))
        with open(os.path.join(d, "README.md"), "w") as fh:
            fh.write(readme(tag, name, MEAS.MEASURED.get(tag)))
        written.append(d)

    for d in written:
        print("wrote " + d)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
