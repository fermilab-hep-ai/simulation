def hv_block(lam, ngauge=3, nflav=2, prob_vector=0.75):
    """Hidden Valley shower + hadronisation settings (spec section S2)."""
    return """
! ---- Hidden Valley shower and hadronisation ----
HiddenValley:fragment   = on
HiddenValley:FSR        = on
HiddenValley:alphaOrder = 1
HiddenValley:Ngauge     = {ngauge}
HiddenValley:nFlav      = {nflav}
HiddenValley:Lambda     = {lam:g}
HiddenValley:pTminFSR   = {ptmin:g}
HiddenValley:probVector = {pv:g}
""".format(ngauge=ngauge, nflav=nflav, lam=lam, ptmin=1.1 * lam, pv=prob_vector)


def hv_spectrum(m_pi, m_qv=None, m_rho=None):
    """
    Dark meson spectrum.

    With nFlav = 2 the hidden sector contains three pseudoscalars (4900111
    piv11, 4900211 piv21, 4900221 piv22) and three vectors (4900113, 4900213,
    4900223).  The off-diagonal 4900211 / 4900213 carry a conserved dark flavour
    and have *empty* decay tables in Pythia's ParticleData -- they are the
    stable dark-matter states.  We set their masses so the spectrum is
    degenerate, and mark them explicitly stable rather than relying on the empty
    table.
    """
    if m_qv is None:
        m_qv = m_pi          # constituent mass, m_rhov ~ 2 m_qv
    if m_rho is None:
        m_rho = 2.0 * m_pi
    return """
! ---- Dark sector spectrum ----
4900101:m0 = {mqv:g}       ! qv1
4900102:m0 = {mqv:g}       ! qv2
4900111:m0 = {mpi:g}       ! piv11 (diagonal, decays)
4900211:m0 = {mpi:g}       ! piv21 (off-diagonal, stable)
4900221:m0 = {mpi:g}       ! piv22 (diagonal, decays)
4900113:m0 = {mrho:g}      ! rhov11 (diagonal, decays)
4900213:m0 = {mrho:g}      ! rhov21 (off-diagonal, stable)
4900223:m0 = {mrho:g}      ! rhov22 (diagonal, decays)

! The off-diagonal (dark-flavoured) states are stable and invisible.  This is
! identical between the ee and mumu samples, so the controlled comparison is
! unaffected, but it does mean a sizeable fraction of the dark shower energy
! never returns to the SM.
4900211:mayDecay = off
4900213:mayDecay = off
""".format(mqv=m_qv, mpi=m_pi, mrho=m_rho)


def hv_decays(products, comment, tau0_mm=None):
    """
    Force every *decaying* dark meson into the same final state.

    The spec fragment only pins 4900111.  With probVector = 0.75 three quarters
    of the dark mesons are vectors, so leaving 4900113 / 4900223 on their
    default flavour-democratic tables would leave most of the visible energy
    flavour-mixed and destroy the ee vs mumu contrast.  Both the pseudoscalars
    and the vectors are therefore forced to the same channel.  meMode 91 is what
    Pythia's own piv table uses.
    """
    ids = [4900111, 4900221, 4900113, 4900223]
    lines = ["\n! ---- Dark meson decays: {0} ----".format(comment)]
    for pid in ids:
        lines.append("{0}:oneChannel = 1 1.0 91 {1}".format(pid, products))
    if tau0_mm is not None:
        lines.append("\n! ---- Proper lifetime, ctau = {0:g} mm ----".format(tau0_mm))
        lines.append("ParticleDecays:limitTau0 = off")
        for pid in ids:
            lines.append("{0}:tau0 = {1:g}".format(pid, tau0_mm))
    return "\n".join(lines) + "\n"


def zv_block(mzp):
    """q qbar -> Zv -> qv qvbar.  No UFO needed; Pythia has this natively."""
    return """
! ---- Hard process: q qbar -> Zv -> qv qvbar ----
! Pythia's native Hidden Valley Z' resonance (4900023).  This replaces the
! MadGraph 'generate p p > zp, zp > qv qv~' step in the spec: the HV module
! already implements it with exactly the 4900xxx conventions the shower expects,
! so no external Hidden Valley UFO is involved and there is no risk of an
! ID-convention mismatch between the hard process and the shower.
HiddenValley:ffbar2Zv = on
4900023:m0     = {m:g}
4900023:mWidth = {w:g}
4900023:mMin   = {mmin:g}
4900023:mMax   = {mmax:g}

! Decay only into the hidden sector (first nFlav dark quark flavours).
4900023:onMode = off
4900023:onIfMatch = 4900101 -4900101
4900023:onIfMatch = 4900102 -4900102
""".format(m=mzp, w=0.01 * mzp, mmin=0.8 * mzp, mmax=1.2 * mzp)


def higgs_portal_block(m_phi, isr_pthat=None):
    """gg -> phi (loop induced) with phi -> qv qvbar, i.e. a Higgs portal."""
    if isr_pthat is None:
        proc = """HiggsSM:gg2H = on"""
        note = """! Inclusive gg -> phi production, NO ISR requirement.  This is deliberate:
! tagging an ISR jet is exactly the trigger handle this analysis is trying to
! avoid needing (spec S1, 'Critical')."""
    else:
        proc = """HiggsSM:gg2Hg(l:t) = on
HiggsSM:qg2Hq(l:t) = on
HiggsSM:qqbar2Hg(l:t) = on
PhaseSpace:pTHatMin = {0:g}""".format(isr_pthat)
        note = """! phi + jet production with a hard recoil jet -- the ISR-tagged control (C1).
! This SHOULD fire the existing HT / single-jet seeds."""
    return """
! ---- Hard process: gg -> phi, phi -> qv qvbar (Higgs portal) ----
{note}
{proc}

25:m0     = {m:g}
25:mMin   = {mmin:g}
25:mMax   = {mmax:g}

! The portal channel is ADDED, not substituted.  gg -> phi production is a
! resonance process whose cross section Pythia builds from the dynamically
! computed phi -> g g partial width, so replacing the whole decay table with
! 'oneChannel' drives Gamma(phi->gg) -- and hence the cross section -- to zero
! ("all processes have vanishing cross sections").  Adding the channel keeps
! the SM table alive for production, and onMode/onIfMatch then leaves only the
! portal open for the decay.  meMode 102 mirrors Pythia's own Zv -> qv qvbar.
25:addChannel = 1 1.0 102 4900101 -4900101
25:onMode = off
25:onIfMatch = 4900101 -4900101
""".format(note=note, proc=proc, m=m_phi,
           mmin=0.5 * m_phi, mmax=1.5 * m_phi)


