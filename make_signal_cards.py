LEPTON = {
    "ee":   ("11 -11", "100% -> e+ e-"),
    "mumu": ("13 -13", "100% -> mu+ mu-"),
}


def s2_points():
    """S2: dark shower -> soft dileptons, matched ee / mumu pairs."""
    out = []
    for mzp in (500, 1000):
        for mpi in (2, 5):
            for flav in ("ee", "mumu"):
                name = "HVdilep_Zp{0}_piD{1}_{2}".format(mzp, mpi, flav)
                products, comment = LEPTON[flav]
                body = (
                    HEADER.format(
                        title="S2 -- Hidden Valley dark shower to soft dileptons ({0})".format(flav),
                        subtitle="m_Zp = {0} GeV, m_piD = {1} GeV, Lambda = {1} GeV".format(mzp, mpi))
                    + zv_block(mzp)
                    + hv_block(lam=float(mpi))
                    + hv_spectrum(float(mpi))
                    + hv_decays(products, comment)
                )
                out.append((name, body))
    return out


def s3_points():
    """S3: displaced soft dimuons -- the S2 mumu chain with a lifetime scan."""
    out = []
    mzp, mpi = 500, 2
    products, comment = LEPTON["mumu"]
    for ctau in (1, 10, 100):
        name = "HVdilep_Zp{0}_piD{1}_mumu_ctau{2}mm".format(mzp, mpi, ctau)
        body = (
            HEADER.format(
                title="S3 -- Displaced soft dimuons, ctau = {0} mm".format(ctau),
                subtitle="Identical to HVdilep_Zp{0}_piD{1}_mumu except for the dark meson proper lifetime".format(mzp, mpi))
            + zv_block(mzp)
            + hv_block(lam=float(mpi))
            + hv_spectrum(float(mpi))
            + hv_decays(products, comment, tau0_mm=float(ctau))
        )
        out.append((name, body))
    return out


def s1_points():
    """S1 approximation: soft high-multiplicity hadronic via a Higgs portal."""
    out = []
    # Dark mesons -> light SM hadrons.  m_X = 2 GeV cannot reach b bbar, so the
    # default (b-dominated) piv table is replaced by light quarks.
    had = ("\n! ---- Dark meson decays: generic hadronic (light quarks) ----\n"
           "4900111:oneChannel = 1 1.0 91 3 -3\n"
           "4900221:oneChannel = 1 1.0 91 3 -3\n"
           "4900113:oneChannel = 1 0.34 91 1 -1\n"
           "4900113:addChannel = 1 0.33 91 2 -2\n"
           "4900113:addChannel = 1 0.33 91 3 -3\n"
           "4900223:oneChannel = 1 0.34 91 1 -1\n"
           "4900223:addChannel = 1 0.33 91 2 -2\n"
           "4900223:addChannel = 1 0.33 91 3 -3\n")

    for m_phi, lam in ((125, 1.0), (125, 2.0), (400, 2.0), (400, 4.0)):
        name = "SUEPlike_HV_mPhi{0}_mX2_Lam{1:g}".format(m_phi, lam)
        body = (
            HEADER.format(
                title="S1 (APPROXIMATION) -- soft high-multiplicity hadronic, Higgs portal",
                subtitle="m_phi = {0} GeV, m_X = 2 GeV, Lambda = {1:g} GeV -- NOT a thermal SUEP shower, see README".format(m_phi, lam))
            + higgs_portal_block(float(m_phi))
            + hv_block(lam=lam)
            + hv_spectrum(2.0)
            + had
        )
        out.append((name, body))

    # C1: the same model with a hard ISR jet required.
    name = "SUEPlike_HV_mPhi125_mX2_Lam2_ISR"
    body = (
        HEADER.format(
            title="C1 (CONTROL) -- ISR-tagged soft high-multiplicity hadronic",
            subtitle="m_phi = 125 GeV, m_X = 2 GeV, Lambda = 2 GeV, pThat > 150 GeV recoil jet")
        + higgs_portal_block(125.0, isr_pthat=150.0)
        + hv_block(lam=2.0)
        + hv_spectrum(2.0)
        + had
    )
    out.append((name, body))
    return out


